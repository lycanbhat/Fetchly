//! Generate client code snippets for a request.

use crate::http::PreparedRequest;
use crate::model::{Body, FormFieldKind, Request};
use crate::vars::VarScope;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language {
    Curl,
    PythonRequests,
    JavaScriptFetch,
    NodeAxios,
    RustReqwest,
    Go,
    HttpRaw,
    HTTPie,
    PowerShell,
}

impl Language {
    pub const ALL: [Language; 9] = [
        Language::Curl,
        Language::PythonRequests,
        Language::JavaScriptFetch,
        Language::NodeAxios,
        Language::RustReqwest,
        Language::Go,
        Language::HttpRaw,
        Language::HTTPie,
        Language::PowerShell,
    ];
    pub fn label(&self) -> &'static str {
        match self {
            Language::Curl => "cURL",
            Language::PythonRequests => "Python - requests",
            Language::JavaScriptFetch => "JavaScript - fetch",
            Language::NodeAxios => "NodeJS - axios",
            Language::RustReqwest => "Rust - reqwest",
            Language::Go => "Go - net/http",
            Language::HttpRaw => "HTTP",
            Language::HTTPie => "HTTPie",
            Language::PowerShell => "PowerShell",
        }
    }
}

/// Headers that are generated by the client itself and add noise to snippets.
fn interesting_headers(p: &PreparedRequest, multipart: bool) -> Vec<(String, String)> {
    p.headers
        .iter()
        .filter(|(k, _)| !k.eq_ignore_ascii_case("user-agent") || !p.headers.iter().any(|(_, v)| v.starts_with("Fetchly/")))
        .filter(|(k, v)| !(k.eq_ignore_ascii_case("user-agent") && v.starts_with("Fetchly/")))
        .filter(|(k, v)| !(k.eq_ignore_ascii_case("accept") && v == "*/*"))
        .filter(|(k, _)| !(multipart && k.eq_ignore_ascii_case("content-type")))
        .cloned()
        .collect()
}

fn sq(s: &str) -> String {
    // single-quote for POSIX shells
    format!("'{}'", s.replace('\'', "'\\''"))
}

fn dq(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| format!("\"{s}\""))
}

/// Resolved multipart fields (key, value, is_file).
fn form_fields(req: &Request, scope: &VarScope) -> Option<Vec<(String, String, bool)>> {
    match &req.body {
        Body::FormData(fields) => Some(
            fields
                .iter()
                .filter(|f| f.enabled && !f.key.is_empty())
                .map(|f| (scope.resolve(&f.key), scope.resolve(&f.value), f.kind == FormFieldKind::File))
                .collect(),
        ),
        _ => None,
    }
}

pub fn generate(lang: Language, req: &Request, p: &PreparedRequest, scope: &VarScope) -> String {
    let form = form_fields(req, scope);
    let headers = interesting_headers(p, form.is_some());
    let body = p.body_text();
    let has_body = !p.body.is_empty();
    let m = p.method.as_str();
    match lang {
        Language::Curl => {
            let mut s = format!("curl --location --request {m} {}", sq(&p.url));
            for (k, v) in &headers {
                s.push_str(&format!(" \\\n  --header {}", sq(&format!("{k}: {v}"))));
            }
            if let Some(form) = &form {
                for (k, v, file) in form {
                    let val = if *file { format!("{k}=@\"{v}\"") } else { format!("{k}={v}") };
                    s.push_str(&format!(" \\\n  --form {}", sq(&val)));
                }
            } else if has_body {
                s.push_str(&format!(" \\\n  --data-raw {}", sq(&body)));
            }
            s
        }
        Language::PythonRequests => {
            let mut s = String::from("import requests\n\n");
            s.push_str(&format!("url = {}\n\n", dq(&p.url)));
            s.push_str("headers = {\n");
            for (k, v) in &headers {
                s.push_str(&format!("    {}: {},\n", dq(k), dq(v)));
            }
            s.push_str("}\n");
            let mut extra = String::new();
            if let Some(form) = &form {
                s.push_str("\ndata = {\n");
                for (k, v, file) in form.iter().filter(|f| !f.2) {
                    let _ = file;
                    s.push_str(&format!("    {}: {},\n", dq(k), dq(v)));
                }
                s.push_str("}\nfiles = [\n");
                for (k, v, _) in form.iter().filter(|f| f.2) {
                    s.push_str(&format!("    ({}, open({}, \"rb\")),\n", dq(k), dq(v)));
                }
                s.push_str("]\n");
                extra = ", data=data, files=files".into();
            } else if has_body {
                s.push_str(&format!("\npayload = {}\n", dq(&body)));
                extra = ", data=payload".into();
            }
            s.push_str(&format!("\nresponse = requests.request({}, url, headers=headers{extra})\n\nprint(response.status_code)\nprint(response.text)\n", dq(m)));
            s
        }
        Language::JavaScriptFetch => {
            let mut s = String::new();
            s.push_str("const headers = new Headers();\n");
            for (k, v) in &headers {
                s.push_str(&format!("headers.append({}, {});\n", dq(k), dq(v)));
            }
            let mut body_line = String::new();
            if let Some(form) = &form {
                s.push_str("\nconst body = new FormData();\n");
                for (k, v, file) in form {
                    if *file {
                        s.push_str(&format!("body.append({}, fileInput.files[0], {});\n", dq(k), dq(v)));
                    } else {
                        s.push_str(&format!("body.append({}, {});\n", dq(k), dq(v)));
                    }
                }
                body_line = "\n  body,".into();
            } else if has_body {
                s.push_str(&format!("\nconst body = {};\n", dq(&body)));
                body_line = "\n  body,".into();
            }
            s.push_str(&format!(
                "\nconst response = await fetch({}, {{\n  method: {},\n  headers,{body_line}\n  redirect: \"follow\",\n}});\n\nconsole.log(response.status);\nconsole.log(await response.text());\n",
                dq(&p.url),
                dq(m)
            ));
            s
        }
        Language::NodeAxios => {
            let mut s = String::from("const axios = require(\"axios\");\n");
            let mut data_line = String::new();
            if let Some(form) = &form {
                s.push_str("const FormData = require(\"form-data\");\nconst fs = require(\"fs\");\n\nconst data = new FormData();\n");
                for (k, v, file) in form {
                    if *file {
                        s.push_str(&format!("data.append({}, fs.createReadStream({}));\n", dq(k), dq(v)));
                    } else {
                        s.push_str(&format!("data.append({}, {});\n", dq(k), dq(v)));
                    }
                }
                data_line = "\n  data,".into();
            } else if has_body {
                s.push_str(&format!("\nconst data = {};\n", dq(&body)));
                data_line = "\n  data,".into();
            }
            s.push_str(&format!("\nconst config = {{\n  method: {},\n  url: {},\n  headers: {{\n", dq(&m.to_lowercase()), dq(&p.url)));
            for (k, v) in &headers {
                s.push_str(&format!("    {}: {},\n", dq(k), dq(v)));
            }
            if form.is_some() {
                s.push_str("    ...data.getHeaders(),\n");
            }
            s.push_str(&format!("  }},{data_line}\n  maxRedirects: 10,\n}};\n\naxios.request(config)\n  .then((res) => console.log(res.status, JSON.stringify(res.data)))\n  .catch((err) => console.error(err));\n"));
            s
        }
        Language::RustReqwest => {
            let mut s = String::from("// Cargo.toml: reqwest = { version = \"0.12\", features = [\"multipart\"] }, tokio = { version = \"1\", features = [\"full\"] }\n\n#[tokio::main]\nasync fn main() -> Result<(), Box<dyn std::error::Error>> {\n    let client = reqwest::Client::new();\n");
            if let Some(form) = &form {
                s.push_str("    let form = reqwest::multipart::Form::new()");
                for (k, v, file) in form {
                    if *file {
                        s.push_str(&format!("\n        .file({}, {}).await?", dq(k), dq(v)));
                    } else {
                        s.push_str(&format!("\n        .text({}, {})", dq(k), dq(v)));
                    }
                }
                s.push_str(";\n");
            }
            s.push_str(&format!(
                "    let response = client\n        .request(reqwest::Method::{}, {})\n",
                if ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"].contains(&m) { m.to_string() } else { format!("from_bytes(b\"{m}\")?") },
                dq(&p.url)
            ));
            for (k, v) in &headers {
                s.push_str(&format!("        .header({}, {})\n", dq(k), dq(v)));
            }
            if form.is_some() {
                s.push_str("        .multipart(form)\n");
            } else if has_body {
                s.push_str(&format!("        .body({})\n", dq(&body)));
            }
            s.push_str("        .send()\n        .await?;\n\n    println!(\"{}\", response.status());\n    println!(\"{}\", response.text().await?);\n    Ok(())\n}\n");
            s
        }
        Language::Go => {
            let mut s = String::from("package main\n\nimport (\n\t\"fmt\"\n\t\"io\"\n\t\"net/http\"\n\t\"strings\"\n)\n\nfunc main() {\n");
            if has_body {
                s.push_str(&format!("\tpayload := strings.NewReader({})\n", go_str(&body)));
            } else {
                s.push_str("\tvar payload io.Reader = nil\n\t_ = strings.NewReader\n");
            }
            s.push_str(&format!("\treq, err := http.NewRequest({}, {}, payload)\n\tif err != nil {{\n\t\tpanic(err)\n\t}}\n", dq(m), dq(&p.url)));
            for (k, v) in p.headers.iter().filter(|(k, v)| !(k.eq_ignore_ascii_case("user-agent") && v.starts_with("Fetchly/"))) {
                s.push_str(&format!("\treq.Header.Add({}, {})\n", dq(k), dq(v)));
            }
            s.push_str("\n\tres, err := http.DefaultClient.Do(req)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\tdefer res.Body.Close()\n\tbody, _ := io.ReadAll(res.Body)\n\tfmt.Println(res.Status)\n\tfmt.Println(string(body))\n}\n");
            s
        }
        Language::HttpRaw => {
            let (host, path) = split_host_path(&p.url);
            let mut s = format!("{m} {path} HTTP/1.1\nHost: {host}\n");
            for (k, v) in &p.headers {
                s.push_str(&format!("{k}: {v}\n"));
            }
            if has_body {
                s.push_str(&format!("Content-Length: {}\n\n{}", p.body.len(), body));
            }
            s
        }
        Language::HTTPie => {
            let mut s = format!("http --follow {m} {}", sq(&p.url));
            for (k, v) in &headers {
                s.push_str(&format!(" \\\n  {}", sq(&format!("{k}:{v}"))));
            }
            if let Some(form) = &form {
                s = s.replacen("http --follow", "http --follow --multipart", 1);
                for (k, v, file) in form {
                    let sep = if *file { "@" } else { "=" };
                    s.push_str(&format!(" \\\n  {}", sq(&format!("{k}{sep}{v}"))));
                }
            } else if has_body {
                s = format!("printf %s {} | {s}", sq(&body));
            }
            s
        }
        Language::PowerShell => {
            let mut s = String::from("$headers = New-Object \"System.Collections.Generic.Dictionary[[String],[String]]\"\n");
            for (k, v) in &headers {
                s.push_str(&format!("$headers.Add(\"{k}\", \"{}\")\n", v.replace('"', "`\"")));
            }
            let mut body_arg = "";
            if has_body && form.is_none() {
                s.push_str(&format!("\n$body = @'\n{body}\n'@\n"));
                body_arg = " -Body $body";
            }
            s.push_str(&format!("\n$response = Invoke-RestMethod '{}' -Method '{m}' -Headers $headers{body_arg}\n$response | ConvertTo-Json\n", p.url));
            s
        }
    }
}

fn go_str(s: &str) -> String {
    if s.contains('`') {
        dq(s)
    } else {
        format!("`{s}`")
    }
}

fn split_host_path(url: &str) -> (String, String) {
    let no_scheme = url.split_once("://").map(|(_, r)| r).unwrap_or(url);
    match no_scheme.find('/') {
        Some(i) => (no_scheme[..i].to_string(), no_scheme[i..].to_string()),
        None => match no_scheme.find('?') {
            Some(i) => (no_scheme[..i].to_string(), format!("/{}", &no_scheme[i..])),
            None => (no_scheme.to_string(), "/".to_string()),
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::http::prepare;
    use crate::model::*;

    #[test]
    fn all_languages_generate() {
        let req = Request {
            method: HttpMethod::Post,
            url: "https://api.example.com/x?a=1".into(),
            headers: vec![KeyValue::new("X-Test", "it's")],
            body: Body::Raw { language: RawLanguage::Json, text: "{\"a\":1}".into() },
            ..Default::default()
        };
        let scope = VarScope::default();
        let p = prepare(&req, &Auth::None, &scope).unwrap();
        for l in Language::ALL {
            let code = generate(l, &req, &p, &scope);
            assert!(code.contains("api.example.com"), "{l:?}");
        }
        let curl = generate(Language::Curl, &req, &p, &scope);
        let round = crate::curl::parse_curl(&curl).unwrap();
        assert_eq!(round.method, HttpMethod::Post);
        assert_eq!(round.url, "https://api.example.com/x?a=1");
    }
}
